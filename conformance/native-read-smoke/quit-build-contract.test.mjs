// Root-only contract tests. The hook-order regression uses one in-memory Rollup bundle;
// it does not build the app, write output files, evaluate generated code or open a browser.
import assert from 'node:assert/strict';
import { Buffer } from 'node:buffer';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { URL, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import {
  QUIT_ENTRY_SIGNATURES,
  assertQuitEntryChunk,
  assertQuitEntryAst,
  assertQuitAsset,
} from './quit-build-contract.mjs';
const facade = '/fixture/conformance/native-read-smoke/quit.tsx';
const entry = () => ({
  type: 'chunk',
  fileName: 'quit.js',
  isEntry: true,
  facadeModuleId: facade,
  exports: ['mountQuitFixture'],
});
const ast = () => ({
  type: 'Program',
  body: [
    {
      type: 'ExportNamedDeclaration',
      source: null,
      declaration: null,
      specifiers: [{ exported: { type: 'Identifier', name: 'mountQuitFixture' } }],
    },
  ],
});
test('strict entry signatures remain explicit in the build configuration', () => {
  assert.equal(QUIT_ENTRY_SIGNATURES, 'strict');
  const source = readFileSync(new URL('./build.mjs', import.meta.url), 'utf8');
  assert.match(source, /preserveEntrySignatures:\s*QUIT_ENTRY_SIGNATURES/);
  assert.match(source, /assertQuitEntryChunk\(entry,/);
  assert.match(source, /assertQuitEntryAst\(this\.parse\(entry\.code\)\)/);
});
test('closed expected entry metadata and actual named export AST are accepted', () => {
  assert.doesNotThrow(() => assertQuitEntryChunk(entry(), facade));
  assert.doesNotThrow(() => assertQuitEntryAst(ast()));
});
test('tree-shaken mount, wrong file/facade or non-entry chunk cannot pass metadata', () => {
  for (const change of [
    { exports: [] },
    { fileName: 'other.js' },
    { isEntry: false },
    { type: 'asset' },
    { facadeModuleId: '/other.tsx' },
  ]) {
    assert.throws(() => assertQuitEntryChunk({ ...entry(), ...change }, facade));
  }
});
test('metadata alone cannot hide absent mount export in generated bytes', () => {
  assert.doesNotThrow(() => assertQuitEntryChunk(entry(), facade));
  assert.throws(() => assertQuitEntryAst({ type: 'Program', body: [] }));
  assert.throws(() =>
    assertQuitEntryAst({
      type: 'Program',
      body: [
        { type: 'ExportDefaultDeclaration', declaration: { id: { name: 'mountQuitFixture' } } },
      ],
    }),
  );
});
test('external re-export and wrong exported name do not supply the local mount contract', () => {
  const external = ast();
  external.body[0].source = { value: 'external' };
  assert.throws(() => assertQuitEntryAst(external));
  const wrong = ast();
  wrong.body[0].specifiers[0].exported.name = 'other';
  assert.throws(() => assertQuitEntryAst(wrong));
});
test('generated export aliases and explicit function exports retain the contract', () => {
  const alias = ast();
  alias.body[0].specifiers[0].local = { name: 'privateMount' };
  assert.doesNotThrow(() => assertQuitEntryAst(alias));
  assert.doesNotThrow(() =>
    assertQuitEntryAst({
      type: 'Program',
      body: [
        {
          type: 'ExportNamedDeclaration',
          source: null,
          declaration: { type: 'FunctionDeclaration', id: { name: 'mountQuitFixture' } },
          specifiers: [],
        },
      ],
    }),
  );
});

test('existing script/style output names keep their bounded classification', () => {
  for (const name of ['quit.js', 'quit-abc.js', 'quit-abc.css']) {
    assert.equal(
      assertQuitAsset(name, name.endsWith('.css') ? 'asset' : 'chunk', 1024),
      'script-or-style',
    );
  }
});
test('observed local WASM names classify only as hashed binary assets', () => {
  assert.equal(assertQuitAsset('quit-BdTvLXeI.wasm', 'asset', 608416), 'wasm');
  assert.equal(assertQuitAsset('quit-CiKcnqpx.wasm', 'asset', 1974495), 'wasm');
  assert.throws(() => assertQuitAsset('quit-BdTvLXeI.wasm', 'chunk', 608416));
  assert.throws(() => assertQuitAsset('quit.wasm', 'asset', 608416));
});
test('WASM admission retains the exact 4 MiB bound and rejects invalid sizes', () => {
  assert.equal(assertQuitAsset('quit-abc.wasm', 'asset', 4 * 1024 * 1024), 'wasm');
  for (const size of [4 * 1024 * 1024 + 1, -1, NaN, Infinity, 1.5]) {
    assert.throws(() => assertQuitAsset('quit-abc.wasm', 'asset', size));
  }
});
test('WASM admission adds no external paths, directories, queries or unrelated extensions', () => {
  for (const name of [
    'https://example.test/quit-abc.wasm',
    '/quit-abc.wasm',
    '../quit-abc.wasm',
    'sub/quit-abc.wasm',
    'sub\\quit-abc.wasm',
    'quit-abc.wasm?url',
    'quit-abc.wasm.js?x',
    'quit-abc.mjs',
    'quit-abc.json',
    'quit-abc.png',
    'quit-abc.wasm/child',
  ]) {
    assert.throws(() => assertQuitAsset(name, 'asset', 1024));
  }
  assert.throws(() => assertQuitAsset('quit-abc.wasm', 'unknown', 1024));
});

test('capture final bytes after the actual Vite preload rewrite phase', async () => {
  const source = readFileSync(new URL('./build.mjs', import.meta.url), 'utf8');
  const configured = /generateBundle:\s*\{\s*order:\s*'(post)'/.exec(source)?.[1];
  assert.equal(configured, 'post');
  assert.match(source, /enforce:\s*'pre'/); // Input pinning still precedes source loading.
  const viteRequire = createRequire(import.meta.resolve('vite'));
  const { rollup } = await import(pathToFileURL(viteRequire.resolve('rollup')).href);
  // Exact helper/marker rewrite observed in the failed emitted entry. The virtual
  // input isolates that +112-byte hook-order failure without the app dependency graph.
  const header =
    'const __vite__mapDeps=(i,m=__vite__mapDeps,d=(m.f||(m.f=["./quit-Df99elDX.js","./quit-BMtQprb4.js"])))=>i.map(i=>d[i]);\n';
  const marker = '__VITE_PRELOAD__';
  const digest = (code) => createHash('sha256').update(code).digest('hex');
  async function captureAt(order) {
    let captured;
    const capture = (_, bundle) => {
      const code = bundle['quit.js'].code;
      captured = { bytes: Buffer.byteLength(code), sha256: digest(code) };
    };
    const bundle = await rollup({
      input: 'virtual-quit',
      preserveEntrySignatures: 'strict',
      plugins: [
        {
          name: 'fixed-virtual-entry',
          resolveId: (id) => (id === 'virtual-quit' ? id : null),
          load: (id) =>
            id === 'virtual-quit'
              ? 'export function mountQuitFixture(){return [__VITE_PRELOAD__,__VITE_PRELOAD__]}'
              : null,
        },
        { name: 'fixture-capture', generateBundle: order ? { order, handler: capture } : capture },
        {
          name: 'observed-vite-preload-phase',
          generateBundle(_, output) {
            const entry = output['quit.js'];
            assert.equal(entry.code.split(marker).length, 3);
            entry.code =
              header + entry.code.replace(marker, '__vite__mapDeps([0,1])').replace(marker, '[]');
          },
        },
      ],
    });
    try {
      const output = (await bundle.generate({ format: 'es', entryFileNames: 'quit.js' })).output;
      const code = output.find((entry) => entry.fileName === 'quit.js').code;
      return { captured, final: { bytes: Buffer.byteLength(code), sha256: digest(code) } };
    } finally {
      await bundle.close();
    }
  }
  const prior = await captureAt(null);
  assert.equal(prior.final.bytes - prior.captured.bytes, 112);
  assert.notEqual(prior.captured.sha256, prior.final.sha256);
  const corrected = await captureAt(configured);
  assert.deepEqual(corrected.captured, corrected.final);
});


test('production fonts are hashed bounded local asset names only', () => {
  assert.equal(assertQuitAsset('quit-s12UeAcm.ttf', 'asset', 194336), 'font');
  for (const name of ['quit.ttf', '../quit-a.ttf', '/quit-a.ttf', 'https://example.test/quit-a.ttf', 'quit-a.ttf?url', 'quit-a.woff']) {
    assert.throws(() => assertQuitAsset(name, 'asset', 194336));
  }
  assert.throws(() => assertQuitAsset('quit-a.ttf', 'chunk', 194336));
  for (const size of [-1, NaN, Infinity, 4 * 1024 * 1024 + 1]) {
    assert.throws(() => assertQuitAsset('quit-a.ttf', 'asset', size));
  }
});
